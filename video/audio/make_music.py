"""Launch-video score (first written for the OtaPath pitch) — an ORIGINAL piece, synthesised from scratch with numpy.
No samples, no third-party recordings: every sound below is generated by this script.

120 BPM · D major · 120.0 s, laid out to the edit:
   0–12   hook      (B minor, heartbeat, tension)        → riser
  12–24   solution  (D major opens up, arpeggio enters)   → 1 s fill
  25–47   feature 1 (full groove)
  47–71   feature 2 (intimate first 4 bars, groove returns)
  71–95   feature 3 (brightest, busiest)
  95–109  build     → 1 s pickup
 110–120  finale    (big D chord, sparkle, ring-out)
Run:  uv run --python 3.12 --with numpy --with scipy --with soundfile python make_music.py
"""
import numpy as np, soundfile as sf
from scipy import signal

SR = 48000
BEAT = 0.5
BAR = 2.0
TOTAL = 120.0
N = int(SR * (TOTAL + 4))
rng = np.random.default_rng(7)

def hz(m): return 440.0 * 2 ** ((m - 69) / 12)

class Bus:
    def __init__(self): self.l = np.zeros(N); self.r = np.zeros(N)
    def add(self, t, x, pan=0.0, gain=1.0):
        i = int(round(t * SR))
        if i >= N or i < 0: return
        x = x[: N - i]
        a = (pan + 1) * np.pi / 4
        self.l[i:i + len(x)] += x * np.cos(a) * gain
        self.r[i:i + len(x)] += x * np.sin(a) * gain
    def stereo(self): return np.stack([self.l, self.r], axis=1)

def env_ad(n, a, d_rate):
    t = np.arange(n) / SR
    return np.minimum(1.0, t / max(a, 1e-4)) * np.exp(-t * d_rate)

def filt(x, kind, fc, order=2):
    sos = signal.butter(order, fc, kind, fs=SR, output="sos")
    return signal.sosfilt(sos, x, axis=0)

# ── instruments ───────────────────────────────────────────────────────────
def pluck(m, dur=0.9, bright=0.35):
    n = int(dur * SR); t = np.arange(n) / SR; f = hz(m)
    x = np.sin(2 * np.pi * f * t) * np.exp(-t * 5.5)
    x += bright * np.sin(2 * np.pi * 2 * f * t) * np.exp(-t * 9)
    x += 0.5 * bright * np.sin(2 * np.pi * 4.0 * f * t) * np.exp(-t * 22)
    x *= np.minimum(1, t / 0.004)
    return x

def bell(m, dur=2.2):
    n = int(dur * SR); t = np.arange(n) / SR; f = hz(m)
    x = np.sin(2 * np.pi * f * t) * np.exp(-t * 2.2)
    x += 0.35 * np.sin(2 * np.pi * 2.0 * f * t) * np.exp(-t * 3.5)
    x += 0.18 * np.sin(2 * np.pi * 3.01 * f * t) * np.exp(-t * 6)
    x += 0.10 * np.sin(2 * np.pi * 5.4 * f * t) * np.exp(-t * 12)
    return x * np.minimum(1, t / 0.006)

def keys(m, dur=3.0):
    """soft felt-piano-ish tone for the hook"""
    n = int(dur * SR); t = np.arange(n) / SR; f = hz(m)
    x = sum((1 / k ** 1.6) * np.sin(2 * np.pi * k * f * (1 + 0.0004 * k * k) * t) * np.exp(-t * (1.1 + 0.55 * k))
            for k in range(1, 7))
    return x * np.minimum(1, t / 0.008)

def pad_note(m, dur, cutoff):
    """three detuned band-limited saws, slow attack/release"""
    n = int((dur + 1.4) * SR); t = np.arange(n) / SR; f0 = hz(m)
    out = np.zeros((n, 2))
    for cents, pan in ((-8, -0.6), (0, 0.0), (8, 0.6)):
        f = f0 * 2 ** (cents / 1200)
        ph = rng.uniform(0, 2 * np.pi)
        v = np.zeros(n)
        k = 1
        while k * f < min(cutoff * 3.5, SR / 2.2):
            v += (1 / k) / (1 + (k * f / cutoff) ** 2.2) * np.sin(2 * np.pi * k * f * t + ph * k)
            k += 1
        a = (pan + 1) * np.pi / 4
        out[:, 0] += v * np.cos(a); out[:, 1] += v * np.sin(a)
    e = np.minimum(1, t / 0.55) * np.minimum(1, np.maximum(0, (dur + 1.3 - t) / 1.3))
    return out * e[:, None]

def bass_note(m, dur):
    n = int(dur * SR); t = np.arange(n) / SR; f = hz(m)
    x = np.sin(2 * np.pi * f * t) + 0.3 * np.sin(2 * np.pi * 2 * f * t) + 0.08 * np.sin(2 * np.pi * 3 * f * t)
    e = np.minimum(1, t / 0.008) * (0.55 + 0.45 * np.exp(-t * 5)) * np.minimum(1, np.maximum(0, (dur - t) / 0.06))
    return np.tanh(1.4 * x * e) / 1.2

def kick(soft=1.0):
    n = int(0.42 * SR); t = np.arange(n) / SR
    f = 46 + 95 * np.exp(-t * 30)
    x = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 8.5)
    x += 0.25 * rng.standard_normal(n) * np.exp(-t * 180)
    return filt(x, "low", 2500 * soft + 400) * 0.95

def snare():
    n = int(0.3 * SR); t = np.arange(n) / SR
    nz = filt(filt(rng.standard_normal(n), "high", 900), "low", 5200) * np.exp(-t * 19)
    body = np.sin(2 * np.pi * (185 + 40 * np.exp(-t * 40)) * t) * np.exp(-t * 26)
    return 0.8 * nz + 0.5 * body

def clap():
    n = int(0.28 * SR); t = np.arange(n) / SR
    nz = filt(filt(rng.standard_normal(n), "high", 1100), "low", 4200)
    e = sum(np.exp(-np.maximum(0, t - d) * 60) * (t >= d) for d in (0.0, 0.011, 0.023)) * 0.5 + np.exp(-t * 16) * (t > 0.03)
    return nz * e * 0.7

def hat(decay=75, hp=8000):
    n = int(0.2 * SR); t = np.arange(n) / SR
    return filt(rng.standard_normal(n), "high", hp, 4) * np.exp(-t * decay) * 0.5

def shaker():
    n = int(0.09 * SR); t = np.arange(n) / SR
    return filt(filt(rng.standard_normal(n), "high", 4500), "low", 9500) * np.sin(np.pi * np.minimum(1, t / 0.085)) ** 2 * 0.4

def riser(dur, f0=300, f1=7000):
    n = int(dur * SR); t = np.arange(n) / SR; p = t / dur
    nz = rng.standard_normal(n)
    out = np.zeros(n); seg = 2048
    for i in range(0, n, seg):   # sweep a band-pass up through the noise
        fc = f0 * (f1 / f0) ** (min(1.0, (i + seg / 2) / n))
        sos = signal.butter(2, [fc * 0.7, min(fc * 1.4, SR / 2.1)], "band", fs=SR, output="sos")
        j0 = max(0, i - seg); chunk = signal.sosfilt(sos, nz[j0:i + seg])
        out[i:i + seg] = chunk[i - j0: i - j0 + seg][: n - i]
    tone = np.sin(2 * np.pi * np.cumsum(180 * (4 ** p)) / SR) * 0.12
    return (out * 0.5 + tone) * p ** 2.2

def impact():
    n = int(3.0 * SR); t = np.arange(n) / SR
    boom = np.sin(2 * np.pi * np.cumsum(38 + 60 * np.exp(-t * 9)) / SR) * np.exp(-t * 1.9)
    crash = filt(rng.standard_normal(n), "high", 3000) * np.exp(-t * 2.6) * 0.22
    thud = filt(rng.standard_normal(n), "low", 300) * np.exp(-t * 14) * 0.9
    return boom + crash + thud

def reverb_ir(decay=2.2, lp=5200):
    n = int(decay * 1.6 * SR); t = np.arange(n) / SR
    ir = rng.standard_normal((n, 2)) * np.exp(-t * (6.9 / decay))[:, None]
    ir = filt(ir, "low", lp); ir[: int(0.012 * SR)] *= 0.1
    return ir / np.sqrt((ir ** 2).sum(axis=0))

def reverb(x, ir, wet):
    y = np.stack([signal.fftconvolve(x[:, c], ir[:, c])[: len(x)] for c in (0, 1)], axis=1)
    return x + wet * y

def delay(x, time, fb=0.35, mix=0.3, pingpong=True):
    d = int(time * SR); y = np.zeros_like(x); src = x.copy()
    for k in range(1, 6):
        g = fb ** (k - 1) * mix
        sh = np.zeros_like(x); sh[d * k:] = src[: len(x) - d * k]
        if pingpong and k % 2: sh = sh[:, ::-1]
        y += sh * g
    return x + filt(y, "low", 3800)

