ENGINE_LABEL = {"jev": "Jev", "gemini-decision-1": "Gemini Decisions"}


def _note(s):
    eng = (s or {}).get("engine")
    return f"Simulation · {ENGINE_LABEL.get(eng, eng)}" if eng else "Simulation"


def _actions_by_id():
    return {a["id"]: a for a in strategy.actions()}


def cite(aid, by_id=None, extra=None):
    by_id = by_id or _actions_by_id()
    assert aid in by_id, f"roadmap action {aid!r} not found in strategy.actions()"
    a = by_id[aid]
    out = {"id": a["id"], "title": a["title"], "title_en": TITLE_EN.get(aid), "page": a["page"], "url": a["url"],
           "responsible": a.get("responsible"), "metric": a.get("metric")}
    if extra:
        out.update(extra)
    return out


def _match_meta(gap_id, aid):
    """Matcher score/confidence for one (gap, action) from the committed Gemini Decisions cache."""
    import matcher
    r = matcher.read_cache().get((aid, gap_id)) or {}
    return {"score": round(r["score"], 2) if r.get("score") is not None else None,
            "confidence": round(r["confidence"], 2) if r.get("confidence") is not None else None,
            "matched_by": "Gemini Decisions",
            "partial_match": r.get("score") is not None and r["score"] < 2.5}


def _matched(gap_id, keep_ids=(), extra=None, max_top=3, by_id=None):
    """Roadmap actions for one gap: matcher top actions (score >= 2.0, max 3, by score); a hand-mapped
    id not in the matcher list is kept only if its matcher score for the gap is >= 1.5."""
    import matcher
    by_id = by_id or _actions_by_id()
    rows = [(r["id"], r["score"]) for r in matcher.ranked(gap_id)[:max_top]]
    have = {a for a, _ in rows}
    for aid in keep_ids:
        sc = matcher.score_for(gap_id, aid)
        if aid not in have and sc is not None and sc >= 1.5:
            rows.append((aid, sc))
    rows.sort(key=lambda t: -t[1])
    return [cite(aid, by_id, (extra or {}) | _match_meta(gap_id, aid)) for aid, _ in rows]


def _sim(prog):
    p = SIM / f"{prog}.json"
    if not p.exists():
        return None
    return json.loads(p.read_text())


def _decomp(prog):
    """Data decomposition (municipality WLS, src/decompose.py) — the 'why' answer that data can back.
    Cervix has no decomposition; the caller falls back to the simulation split."""
    try:
        import decompose
        return decompose.decompose(prog)
    except KeyError:
        return None


def recommend(prog, code):
    """Full recommendation payload for one programme and county."""
    ind = PROGRAMMES[prog]
    gap = ds.screening_gap(ind, code)
    s = _sim(prog)
    row = s["levels"]["county"]["rows"].get(code) if s else None
    validation = s["validation"] if s else None

    sim_comp, sim_other = (row or {}).get("composition_gap"), (row or {}).get("other_gap")
    sim_real = (row or {}).get("real")
    sim_nat = (s or {}).get("levels", {}).get("county", {}).get("national_real")
    # The driver and the unexplained-gap action key off the DATA decomposition; the simulation
    # split stays available as sim_split for the "who skips / what stops them" question.
    D = _decomp(prog)
    drow = (D or {}).get("rows", {}).get(code)
    if drow:
        comp, other = drow["composition_gap"], drow["unexplained_gap"]
        real, nat_real = drow["real"], D["national_real"]
    else:
        comp, other = sim_comp, sim_other
        real, nat_real = sim_real, sim_nat
    at_national = real is not None and nat_real is not None and abs(real - nat_real) <= NATIONAL_BAND_PTS
    driver_assumption = None
    if gap and gap["rate"] >= gap["target"]:
        driver = "on_target"
    elif at_national:
        driver = "national"; driver_assumption = NATIONAL_ASSUMPTION
    elif other is not None and comp is not None and other < 0 and abs(other) > abs(comp):
        driver = "services"
    else:
        driver = "population"
    # plain-word headline key for step 2a — share of the real-vs-Finland gap each side explains
    headline = None
    if drow and real is not None and nat_real is not None and real < nat_real and comp is not None and other is not None:
        tg = abs(real - nat_real)
        if tg and abs(comp) / tg >= 0.6:
            headline = "mostly_population"
        elif tg and other < 0 and abs(other) / tg >= 0.6:
            headline = "mostly_unexplained"
        elif tg:
            headline = "both"

    by_id = _actions_by_id()
    scenarios = []
    for sc, res in sorted(((sc, res) for sc, res in (s or {}).get("scenarios", {}).items()),
                          key=lambda kv: -(kv[1]["levels"]["county"].get(code, {}).get("extra_people_per_year") or 0)):
        m = SCENARIO_ACTIONS[sc]
        per = res["levels"]["county"].get(code, {})
        extra = per.get("extra_people_per_year")
        missing = (gap or {}).get("missing_per_year")
        scenarios.append({"scenario": sc, "label": res["label"], "short": m["short"],
                          "delta_points": per.get("delta_points"), "extra_people_per_year": extra,
                          "share_of_missing": round(100 * extra / missing) if extra and missing else None,
                          "actions": _matched(m["gap"], m["actions"], by_id=by_id), "assumption": None,
                          "note": _note(s)})

    pathway_actions = []
    if driver == "national":
        pathway_actions.append(cite(NATIONAL_ACTION, by_id,
                                    {"why": NATIONAL_WHY, "stage": "detection"} |
                                    _match_meta("screening_service", NATIONAL_ACTION)))
    if other is not None and comp is not None and other < 0 and abs(other) > abs(comp):
        pathway_actions += _matched("screening_service", (MONITORING_ACTION,), by_id=by_id,
                                    extra={"why": "The unexplained part of the gap is larger than the population "
                                                  "part; county-level screening data and targeted organisation "
                                                  "are the early-warning levers.",
                                           "stage": "detection"})

    surv = None
    skey = SURVIVAL.get(prog)
    if skey:
        v = ds.values(skey, "county")
        r = v["values"].get(code)
        if r and v["national"] is not None:
            surv = {"key": skey, "value": r["value"], "national": v["national"],
                    "delta": round(r["value"] - v["national"], 1), "below_national": r["value"] < v["national"],
                    "year": v["year"], "source": v["source"]}
            if r["value"] < v["national"]:
                pathway_actions += _matched(GOAL3_GAP, GOAL3_ACTIONS, by_id=by_id,
                                            extra={"why": GOAL3_LIMITATION, "stage": "outcome"})

    for qkey, q in QUEUE_ACTIONS.items():
        v = ds.values(qkey, "county")
        r = v["values"].get(code)
        if r and v["national"] is not None and r["value"] - v["national"] >= QUEUE_MIN_POINTS:
            small = r["abs_value"] is not None and r["abs_value"] < SMALL_N
            pathway_actions += _matched(q["gap"], q["ids"], by_id=by_id,
                                        extra={"why": q["why"], "assumption": q["assumption"], "stage": q["stage"],
                                               "small_numbers": f"n = {int(r['abs_value'])}" if small else None})

    return {"programme": prog, "code": code, "name": ds.short_names().get(code, code),
            "screening": {k: gap[k] for k in ("rate", "target", "missing_per_year", "invited")} | {"source": gap["source"]} if gap else None,
            "split": {"composition_gap": comp, "other_gap": other,
                      "total_gap": round(real - nat_real, 1) if real is not None and nat_real is not None else None,
                      "comp_pts": round(abs(comp), 1) if comp is not None else None,
                      "other_pts": round(abs(other), 1) if other is not None else None,
                      "total_pts": round(abs(real - nat_real), 1) if real is not None and nat_real is not None else None,
                      "composition_gap_90": drow["composition_gap_90"] if drow else None,
                      "expected": drow["expected"] if drow else (row or {}).get("expected"),
                      "real": real, "national_real": nat_real,
                      "r2": (D or {}).get("r2"), "r2_pct": round(100 * D["r2"]) if D else None,
                      "n_municipalities": (D or {}).get("n_municipalities"),
                      "driver": driver, "headline": headline,
                      "assumption": driver_assumption,
                      "note": "Data · municipality WLS on composition" if drow else _note(s),
                      "method": (D or {}).get("method"), "source": (D or {}).get("source")},
            "sim_split": {"composition_gap": sim_comp, "other_gap": sim_other,
                          "expected": (row or {}).get("expected"), "real": sim_real,
                          "total_gap": round(sim_real - sim_nat, 1) if sim_real is not None and sim_nat is not None else None,
                          "note": _note(s), "validation": validation},
            "scenarios": scenarios,
            "pathway_actions": pathway_actions,
            "survival": surv}


def brief(progs=("breast", "bowel"), n=3):
    """The n counties with the largest missing_per_year per programme, trimmed to top scenario + driver."""
    out = []
    for prog in progs:
        ind = PROGRAMMES[prog]
        v = ds.values(ind, "county")
        ranked = sorted((g for c in v["values"] if (g := ds.screening_gap(ind, c)) and g["missing_per_year"] > 0),
                        key=lambda g: -g["missing_per_year"])
        counties = []
        for g in ranked[:n]:
            r = recommend(prog, g["code"])
            counties.append({"code": r["code"], "name": r["name"], "screening": r["screening"],
                             "split": r["split"], "top_scenario": r["scenarios"][0] if r["scenarios"] else None,
                             "survival": r["survival"]})
        s = _sim(prog)
        out.append({"programme": prog, "validation": s["validation"] if s else None,
                    "national": v["national"], "target": v["target"],
                    "counties": counties, "note": _note(s)})
    return {"programmes": out}
