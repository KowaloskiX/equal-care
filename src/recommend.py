"""Recommendations: turn a county's screening gap into cited roadmap actions.

Every recommendation quotes a numbered action of the implementation roadmap (id + page + url from
strategy.actions(); ids are asserted to exist). Numbers come from datastore and the committed
simulation; nothing here is generated by a model.
"""
import json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import datastore as ds
import strategy

ROOT = Path(__file__).resolve().parent.parent
SIM = ROOT / "data/sim"

PROGRAMMES = {"breast": "screen_breast", "bowel": "screen_bowel", "cervix": "screen_cervix"}
SURVIVAL = {"breast": "surv_breast", "bowel": "surv_bowel"}

# ASSUMPTION: the roadmap does not name SMS reminders / evening slots / mobile units; 2.4.1 is the action
# through which a county sets such service requirements in procurement.
SERVICE_ASSUMPTION = ("The roadmap does not name SMS reminders / evening slots / mobile units; 2.4.1 is the "
                      "action through which a county sets such service requirements in procurement.")
SCENARIO_ACTIONS = {
    "own_language": {"actions": ["1.3.1"], "assumption": None, "short": "Own language"},
    "sms_reminder": {"actions": ["2.4.1", "1.1.1"], "assumption": SERVICE_ASSUMPTION, "short": "SMS reminder"},
    "evening_slots": {"actions": ["2.4.1", "1.1.1"], "assumption": SERVICE_ASSUMPTION, "short": "Evening slots"},
    "mobile_unit": {"actions": ["2.4.1", "1.1.1"], "assumption": SERVICE_ASSUMPTION, "short": "Mobile unit"},
}
MONITORING_ACTION = "2.4.5"     # monthly county-level screening data / real-time status from the Cancer Registry
# ASSUMPTION: a county within 1 point of the national rate is treated as a national-level gap, not a local one.
NATIONAL_BAND_PTS = 1.0
NATIONAL_ASSUMPTION = "Counties within 1 point of the national rate are treated as national-level gaps (assumption: 1-point band)."
NATIONAL_ACTION = "2.4.1"
NATIONAL_WHY = ("The county is at the national level; the gap to 80 % is national, so the lever is the national "
                "screening quality handbooks in procurement.")
GOAL3_ACTIONS = ["3.2.1", "3.2.2"]
GOAL3_LIMITATION = ("Stage at diagnosis and time from diagnosis to treatment are not published by county, so the "
                    "survival gap cannot be located on the pathway with public data; the quality registry is what "
                    "would close this gap.")
# ASSUMPTION: waiting lists cover non-urgent oncology care; urgent cancer treatment is not in this measure, so this
# is a proxy for capacity, not time from diagnosis to treatment.
WAIT_PROXY = ("Waiting lists cover non-urgent oncology care; urgent cancer treatment is not in this measure, so this "
              "is a proxy for capacity, not time from diagnosis to treatment.")
# ASSUMPTION: a queue indicator triggers an action only when it is at least 1 percentage point worse than Finland,
# so rounding-level differences (0.4 % vs 0.2 %) do not produce recommendations; below 30 patients it is flagged.
QUEUE_MIN_POINTS = 1.0
SMALL_N = 30
QUEUE_ACTIONS = {
    "onc_ref_21": {"ids": ["2.5.2"], "assumption": None, "stage": "referral",   # standardised referral criteria
                   "why": "Oncology referrals are processed in over 21 days more often than nationally; standardised "
                          "referral criteria are the lever for a smooth transition to specialist care."},
    "onc_wait_90": {"ids": ["3.1.2", "3.1.4"], "assumption": WAIT_PROXY, "stage": "treatment",
                    "why": "A larger share of oncology patients than nationally waits over 90 days for treatment; "
                           "regional care pathways and national quality targets are the lever."},
}

# English titles for the cited roadmap actions (the roadmap itself is Finnish).
TITLE_EN = {
    "1.1.1": "Involve residents and patients in developing screening and other preventive services",
    "1.3.1": "Raise screening participation of language groups through targeted, community-based communication",
    "2.4.1": "Apply the screening quality handbooks in procurement and steering",
    "2.4.5": "Use screening-register data with the counties (monthly county-level reporting)",
    "2.5.2": "Standardised referral criteria for a smooth transition to specialised care",
    "3.1.2": "Cancer-specific care pathway descriptions applied as regional pathways",
    "3.1.4": "National quality and effectiveness targets and monitoring metrics for care pathways",
    "3.2.1": "Legal basis for a cancer care quality registry at the Finnish Cancer Registry",
    "3.2.2": "Systematic peer comparison of quality-registry data between counties",
}

ENGINE_LABEL = {"jev": "Jev", "gemini-decision-1": "Gemini Decisions"}


def _note(s):
    eng = (s or {}).get("engine")
    return f"Simulation · {ENGINE_LABEL.get(eng, eng)}" if eng else "Simulation"


def _actions_by_id():
    return {a["id"]: a for a in strategy.actions()}


def cite(aid, by_id=None, extra=None):
    by_id = by_id or _actions_by_id()
    assert aid in by_id, f"roadmap action {aid!r} not found in strategy.actions()"
    a = by_id[aid]
    out = {"id": a["id"], "title": a["title"], "title_en": TITLE_EN.get(aid), "page": a["page"], "url": a["url"],
           "responsible": a.get("responsible"), "metric": a.get("metric")}
    if extra:
        out.update(extra)
    return out


def _sim(prog):
    p = SIM / f"{prog}.json"
    if not p.exists():
        return None
    return json.loads(p.read_text())


def _decomp(prog):
    """Data decomposition (municipality WLS, src/decompose.py) — the 'why' answer that data can back.
    Cervix has no decomposition; the caller falls back to the simulation split."""
    try:
        import decompose
        return decompose.decompose(prog)
    except KeyError:
        return None


def recommend(prog, code):
    """Full recommendation payload for one programme and county."""
    ind = PROGRAMMES[prog]
    gap = ds.screening_gap(ind, code)
    s = _sim(prog)
    row = s["levels"]["county"]["rows"].get(code) if s else None
    validation = s["validation"] if s else None

    sim_comp, sim_other = (row or {}).get("composition_gap"), (row or {}).get("other_gap")
    sim_real = (row or {}).get("real")
    sim_nat = (s or {}).get("levels", {}).get("county", {}).get("national_real")
    # The driver and the unexplained-gap action key off the DATA decomposition; the simulation
    # split stays available as sim_split for the "who skips / what stops them" question.
    D = _decomp(prog)
    drow = (D or {}).get("rows", {}).get(code)
    if drow:
        comp, other = drow["composition_gap"], drow["unexplained_gap"]
        real, nat_real = drow["real"], D["national_real"]
    else:
        comp, other = sim_comp, sim_other
        real, nat_real = sim_real, sim_nat
    at_national = real is not None and nat_real is not None and abs(real - nat_real) <= NATIONAL_BAND_PTS
    driver_assumption = None
    if gap and gap["rate"] >= gap["target"]:
        driver = "on_target"
    elif at_national:
        driver = "national"; driver_assumption = NATIONAL_ASSUMPTION
    elif other is not None and comp is not None and other < 0 and abs(other) > abs(comp):
        driver = "services"
    else:
        driver = "population"

    by_id = _actions_by_id()
    scenarios = []
    for sc, res in sorted(((sc, res) for sc, res in (s or {}).get("scenarios", {}).items()),
                          key=lambda kv: -(kv[1]["levels"]["county"].get(code, {}).get("extra_people_per_year") or 0)):
        m = SCENARIO_ACTIONS[sc]
        per = res["levels"]["county"].get(code, {})
        extra = per.get("extra_people_per_year")
        missing = (gap or {}).get("missing_per_year")
        scenarios.append({"scenario": sc, "label": res["label"], "short": m["short"],
                          "delta_points": per.get("delta_points"), "extra_people_per_year": extra,
                          "share_of_missing": round(100 * extra / missing) if extra and missing else None,
                          "actions": [cite(aid, by_id) for aid in m["actions"]], "assumption": m["assumption"],
                          "note": _note(s)})

    pathway_actions = []
    if driver == "national":
        pathway_actions.append(cite(NATIONAL_ACTION, by_id, {"why": NATIONAL_WHY, "stage": "detection"}))
    if other is not None and comp is not None and other < 0 and abs(other) > abs(comp):
        pathway_actions.append(cite(MONITORING_ACTION, by_id,
                                    {"why": "The unexplained part of the gap is larger than the population part; "
                                            "monthly county-level screening data is the early-warning action.",
                                     "stage": "detection"}))

    surv = None
    skey = SURVIVAL.get(prog)
    if skey:
        v = ds.values(skey, "county")
        r = v["values"].get(code)
        if r and v["national"] is not None:
            surv = {"key": skey, "value": r["value"], "national": v["national"],
                    "delta": round(r["value"] - v["national"], 1), "below_national": r["value"] < v["national"],
                    "year": v["year"], "source": v["source"]}
            if r["value"] < v["national"]:
                pathway_actions += [cite(aid, by_id, {"why": GOAL3_LIMITATION, "stage": "outcome"})
                                    for aid in GOAL3_ACTIONS]

    for qkey, q in QUEUE_ACTIONS.items():
        v = ds.values(qkey, "county")
        r = v["values"].get(code)
        if r and v["national"] is not None and r["value"] - v["national"] >= QUEUE_MIN_POINTS:
            small = r["abs_value"] is not None and r["abs_value"] < SMALL_N
            pathway_actions += [cite(aid, by_id, {"why": q["why"], "assumption": q["assumption"], "stage": q["stage"],
                                                  "small_numbers": f"n = {int(r['abs_value'])}" if small else None})
                                for aid in q["ids"]]

    return {"programme": prog, "code": code, "name": ds.short_names().get(code, code),
            "screening": {k: gap[k] for k in ("rate", "target", "missing_per_year", "invited")} | {"source": gap["source"]} if gap else None,
            "split": {"composition_gap": comp, "other_gap": other,
                      "total_gap": round(real - nat_real, 1) if real is not None and nat_real is not None else None,
                      "comp_pts": round(abs(comp), 1) if comp is not None else None,
                      "other_pts": round(abs(other), 1) if other is not None else None,
                      "total_pts": round(abs(real - nat_real), 1) if real is not None and nat_real is not None else None,
                      "composition_gap_90": drow["composition_gap_90"] if drow else None,
                      "expected": drow["expected"] if drow else (row or {}).get("expected"),
                      "real": real, "national_real": nat_real,
                      "r2": (D or {}).get("r2"), "r2_pct": round(100 * D["r2"]) if D else None,
                      "n_municipalities": (D or {}).get("n_municipalities"),
                      "driver": driver,
                      "assumption": driver_assumption,
                      "note": "Data · municipality WLS on composition" if drow else _note(s),
                      "method": (D or {}).get("method"), "source": (D or {}).get("source")},
            "sim_split": {"composition_gap": sim_comp, "other_gap": sim_other,
                          "expected": (row or {}).get("expected"), "real": sim_real,
                          "total_gap": round(sim_real - sim_nat, 1) if sim_real is not None and sim_nat is not None else None,
                          "note": _note(s), "validation": validation},
            "scenarios": scenarios,
            "pathway_actions": pathway_actions,
            "survival": surv}


def brief(progs=("breast", "bowel"), n=3):
    """The n counties with the largest missing_per_year per programme, trimmed to top scenario + driver."""
    out = []
    for prog in progs:
        ind = PROGRAMMES[prog]
        v = ds.values(ind, "county")
        ranked = sorted((g for c in v["values"] if (g := ds.screening_gap(ind, c)) and g["missing_per_year"] > 0),
                        key=lambda g: -g["missing_per_year"])
        counties = []
        for g in ranked[:n]:
            r = recommend(prog, g["code"])
            counties.append({"code": r["code"], "name": r["name"], "screening": r["screening"],
                             "split": r["split"], "top_scenario": r["scenarios"][0] if r["scenarios"] else None,
                             "survival": r["survival"]})
        s = _sim(prog)
        out.append({"programme": prog, "validation": s["validation"] if s else None,
                    "national": v["national"], "target": v["target"],
                    "counties": counties, "note": _note(s)})
    return {"programmes": out}
